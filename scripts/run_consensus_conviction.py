FIRM_CSV = Path("data/sentiment_aapl_firm.csv")


@dataclass
class Cfg:
    ticker: str
    horizon: int
    seed: int
    model: str
    split: str  # "701515" | "wf"
    epochs: int = 120


def attach_local_sentiment(df: pd.DataFrame, ticker: str) -> pd.DataFrame:
    """Merge firm-level local sentiment (AAPL) or cached GDELT tone (Samsung)."""
    if ticker == "AAPL" and FIRM_CSV.exists():
        firm = pd.read_csv(FIRM_CSV)
        firm["Date"] = pd.to_datetime(firm["Date"]).dt.normalize()
        firm = firm.sort_values("Date")
        # strictly past values: ffill, and counts are real filing counts
        daily = firm.set_index("Date").reindex(df["Date"]).ffill()
        df = df.copy()
        df["Sentiment"] = daily["polarity"].values
        df["NewsCount"] = daily["count"].fillna(0).values
    else:
        # cached GDELT tone (already lagged by creation); counts unavailable
        if "Sentiment" not in df.columns:
            df["Sentiment"] = np.nan
        df["NewsCount"] = 0.0
    return df


def prepare(df: pd.DataFrame, cfg: Cfg) -> SplitData:
    from src.vol_gated_gru import prepare_split_data

    split = prepare_split_data(
        df,
        features="price+tech+ohlcv_volnorm+sentiment",
        horizon=cfg.horizon,
    )
    return split


def _drop_sent(split: SplitData) -> SplitData:
    n = split.n_sent
    if n == 0:
        return split
    return SplitData(
        split.x_train[:, :, :-n], split.y_train, split.p_train, split.prev_train,
        split.x_val[:, :, :-n], split.y_val, split.p_val, split.prev_val,
        split.x_test[:, :, :-n], split.y_test, split.p_test, split.prev_test,
        split.scaler, split.feature_names[:-n], 0,
    )


def train_predict(cfg: Cfg, df: pd.DataFrame) -> dict[str, Any]:
    set_seed(cfg.seed)
    split = prepare(df, cfg)

    if cfg.model == "no_sent_mse":
        s = _drop_sent(split)
        model = BaselineGRU(input_size=s.x_train.shape[2])
        loss = "mse"
        gated = False
    elif cfg.model == "no_sent_dir_margin":
        s = _drop_sent(split)
        model = BaselineGRU(input_size=s.x_train.shape[2])
        loss = "vol_huber_margin"
        gated = False
    else:  # concat_sent_gru
        s = split
        model = BaselineGRU(input_size=s.x_train.shape[2])
        loss = "mse"
        gated = False

    hist = train_model(model, s, use_sentiment=(cfg.model == "concat_sent_gru"),
                       gated=gated, epochs=cfg.epochs, seed=cfg.seed,
                       loss_kind=loss)
    pred_test = predict(model, s.x_test, use_sentiment=(cfg.model == "concat_sent_gru"),
                        n_sent=s.n_sent, gated=gated)
    pred_val = predict(model, s.x_val, use_sentiment=(cfg.model == "concat_sent_gru"),
                       n_sent=s.n_sent, gated=gated)
    return {
        "split": s,
        "pred_test": pred_test,
        "pred_val": pred_val,
        "hist": hist,
    }


def evaluate(mask: np.ndarray, y: np.ndarray, pred: np.ndarray,
             baseline_err: np.ndarray | None) -> dict[str, Any]:
    y = np.asarray(y, dtype=float).ravel()[mask]
    p = np.asarray(pred, dtype=float).ravel()[mask]
    if len(y) == 0:
        return {"n": 0}
    act = np.sign(y)
    prd = np.sign(p)
    dir_acc = float(np.mean(act == prd))
    majority = max(float(np.mean(act > 0)), float(np.mean(act < 0)))
    excess = dir_acc - majority
    r = np.expm1(y)
    gross = float(np.sum(prd * r))
    flips = float(np.sum(np.abs(np.diff(prd)))) if len(prd) > 1 else 0.0
    turnover = flips / max(len(prd) - 1, 1)
    net = gross - COST_BPS_PER_SIDE * flips
    e = (y - p) ** 2
    e_base = y ** 2
    z_base, p_base = hac_dm(e, e_base)
    z_ref = p_ref = float("nan")
    if baseline_err is not None:
        z_ref, p_ref = hac_dm(e, baseline_err[mask])
    return {
        "n": int(len(y)),
        "dir_acc": dir_acc,
        "majority_base_rate": majority,
        "excess_dir_acc": excess,
        "dm_vs_base": z_base,
        "dm_p_vs_base": p_base,
        "dm_vs_baseline": z_ref,
        "dm_p_vs_baseline": p_ref,
        "turnover": turnover,
        "net_return_5bps": net,
        "errors": e,
    }


def conviction_q_val(pred_val: np.ndarray, y_val: np.ndarray,
                     grid=None) -> tuple[float, float]:
    """Choose |pred| quantile on validation maximizing net return."""
    if grid is None:
        grid = np.arange(0.0, 0.96, 0.05)
    best_q, best_net = 0.0, -np.inf
    for q in grid:
        thr = np.quantile(np.abs(pred_val), q) if len(pred_val) else 0.0
        sig = np.where(np.abs(pred_val) > thr, np.sign(pred_val), 0.0)
        r = np.expm1(y_val)
        gross = float(np.sum(sig * r))
        flips = float(np.sum(np.abs(np.diff(sig)))) if len(sig) > 1 else 0.0
        net = gross - COST_BPS_PER_SIDE * flips
        if net > best_net:
            best_net, best_q = net, float(q)
    return best_q, best_net


def run_wf_folds(cfg: Cfg, df: pd.DataFrame) -> list[SplitData]:
    """Expanding walk-forward: per-fold train-only scaler, chronological OOS."""
    from src.vol_gated_gru import build_feature_frame, make_windows

    fdf, _, _ = build_feature_frame(df, include_sentiment=True)
    cols = list(fdf.columns)
    m = fdf[cols].to_numpy(float)
    n = len(m)
    n_folds = 4
    first_test = int(n * 0.4)
    seg = (n - first_test) // n_folds
    folds = []
    for k in range(n_folds):
        t0 = first_test + k * seg
        t1 = n if k == n_folds - 1 else t0 + seg
        scaler = fit_scaler(m[:t0])
        scaled = scaler.transform(m)
        xt, yt, pt, prevt = make_windows(scaled[:t0], m[:t0, 0], 30, cfg.horizon)
        val_n = max(1, int(len(xt) * 0.15))
        x_tr, y_tr = xt[:-val_n], yt[:-val_n]
        x_va, y_va = xt[-val_n:], yt[-val_n:]
        xe, ye, pe, preve = make_windows(scaled[t0:t1], m[t0:t1, 0], 30, cfg.horizon)
        n_sent = (len(cols) - cols.index("sent_tone")) if "sent_tone" in cols else 0
        folds.append(SplitData(
            x_tr, y_tr, pt[:-val_n], prevt[:-val_n],
            x_va, y_va, pt[-val_n:], prevt[-val_n:],
            xe, ye, pe, preve, scaler, cols, n_sent,
        ))
    return folds


def _run_split(cfg: Cfg, df: pd.DataFrame,
               wf: bool) -> dict[str, Any]:
    """Train per seed (or per WF fold), return pooled OOS predictions + mets."""
    if not wf:
        out = train_predict(cfg, df)
        split = out["split"]
        y = split.y_test[:, 0]
        p = out["pred_test"]
        prev = split.prev_test
        q, _ = conviction_q_val(out["pred_val"], split.y_val[:, 0])
        n_tot = len(y)
        extra = {"q_val": q, "n_test_total": n_tot, "split": "701515"}
        return {"y": y, "p": p, "prev": prev, "n_tot": n_tot, "extra": extra}
    ys, ps, prevs, n_tot = [], [], [], 0
    qs = []
    for fold in run_wf_folds(cfg, df):
        model = BaselineGRU(input_size=fold.x_train.shape[2])
        loss = "mse" if cfg.model != "no_sent_dir_margin" else "vol_huber_margin"
        use_sent = cfg.model == "concat_sent_gru"
        train_model(model, fold, use_sentiment=use_sent, gated=False,
                    epochs=cfg.epochs, seed=cfg.seed, loss_kind=loss)
        p = predict(model, fold.x_test, use_sentiment=use_sent,
                    n_sent=fold.n_sent, gated=False)
        ys.append(fold.y_test[:, 0]); ps.append(p); prevs.append(fold.prev_test)
        n_tot += len(p)
        q, _ = conviction_q_val(
            predict(model, fold.x_val, use_sentiment=use_sent,
                    n_sent=fold.n_sent, gated=False),
            fold.y_val[:, 0])
        qs.append(q)
    return {"y": np.concatenate(ys), "p": np.concatenate(ps),
            "prev": np.concatenate(prevs), "n_tot": n_tot,
            "extra": {"q_val": float(np.mean(qs)),
                       "n_test_total": n_tot, "split": "wf"}}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tickers", default="AAPL,005930.KS")
    ap.add_argument("--horizons", default="3,5")
    ap.add_argument("--seeds", default="42,123,2026")
    ap.add_argument("--epochs", type=int, default=120)
    args = ap.parse_args()

    tickers = args.tickers.split(",")
    horizons = [int(h) for h in args.horizons.split(",")]
    seeds = [int(s) for s in args.seeds.split(",")]

    rows: list[dict[str, Any]] = []
    print("# Consensus & Conviction (verified) — seeds 42/123/2026", flush=True)
    for split_type in ("701515", "wf"):
        for ticker in tickers:
            df = load_ohlcv(ticker)
            df = attach_local_sentiment(df, ticker)
            for horizon in horizons:
                for model in MODELS:
                    per_seed: list[dict[str, Any]] = []
                    for seed in seeds:
                        cfg = Cfg(ticker, horizon, seed, model, split_type,
                                  args.epochs)
                        out = _run_split(cfg, df, wf=(split_type == "wf"))
                        y, p = out["y"], out["p"]
                        e = (y - p) ** 2
                        e_base = y ** 2
                        full = evaluate(np.ones(len(y), bool), y, p, e_base)
                        # conviction mask from val-quantile
                        q = out["extra"]["q_val"]
                        thr = np.quantile(np.abs(p), q)
                        conv = evaluate(np.abs(p) > thr, y, p, e_base)
                        per_seed.append({
                            "y": y.tolist(), "p": p.tolist(),
                            "full": full, "conviction": conv,
                            **out["extra"],
                        })
                    # 3/3 consensus
                    n = min(len(s["y"]) for s in per_seed)
                    y0 = np.array(per_seed[0]["y"][:n])
                    preds = np.array([s["p"][:n] for s in per_seed])
                    agree = np.all(np.sign(preds) == np.sign(preds[0]), axis=0)
                    cons_eval = evaluate(agree, y0, preds[0], y0 ** 2)
                    rows.append({
                        "split": split_type, "ticker": ticker,
                        "horizon": horizon, "model": model,
                        "seeds": seeds,
                        "consensus_3of3": cons_eval,
                        "per_seed": per_seed,
                    })
                    print(f"{split_type} {ticker} h={horizon} {model}: "
                          f"full {np.mean([s['full']['dir_acc'] for s in per_seed]):.4f} "
                          f"| consensus n={cons_eval['n']} "
                          f"dir={cons_eval['dir_acc']:.4f} "
                          f"net={cons_eval['net_return_5bps']:.4f}", flush=True)
    with open(OUT_DIR / "summary.json", "w") as f:
        json.dump(rows, f, indent=2, default=str)
    print(f"\nsummary saved -> {OUT_DIR / 'summary.json'}")


if __name__ == "__main__":
    main()
