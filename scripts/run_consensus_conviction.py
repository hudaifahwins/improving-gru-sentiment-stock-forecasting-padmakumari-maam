"""Seed-consensus & validation-calibrated conviction filters (paper-upgrade).

Evaluates the strongest existing architectures (no_sent_mse, no_sent_dir_margin,
concat_sent_gru) under three OOS decision rules:

  (a) Full coverage (trade every bar)
  (b) 3/3 multi-seed sign agreement (trade only when all seeds agree)
  (c) Validation-calibrated |pred| top-quantile conviction (q_val fit on train/val)

On AAPL and 005930.KS, h=3/5, non-overlapping windows, seeds 42/123/2026,
under both 70/15/15 and expanding walk-forward OOS.

Sentiment inputs
----------------
- AAPL: local firm-level Loughran-McDonald polarity from real SEC 8-K text
  (data/sentiment_aapl_firm.csv, generated by src/local_finbert_sentiment.py);
  daily series forward-fill strictly from the past; counts are real filing counts.
- 005930.KS: cached GDELT tone (English query) — no firm-level SEC text exists
  for a Korean issuer, documented as coverage gap (no fabrication).

Outputs: results/consensus_conviction/summary.json (gitignored) + markdown tables.
"""

